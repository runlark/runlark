#!/usr/bin/env node
// Every hand-written file in the Git index stays at or below 20000 bytes (5000 tokens, 1 token = 4
// bytes). The index, not a diff, is checked: pre-commit, pre-push and a shallow CI checkout then
// give one answer without a base revision. Files over the limit before the rule existed are listed
// in file-limit.baseline; an entry that no longer exceeds the limit fails, so the list only shrinks.
import { spawn, spawnSync } from "node:child_process";

const LIMIT = 20_000;
const BASELINE = "file-limit.baseline";
const HEADER_BYTES = 8000;

const git = (cwd, args, input) => {
    const result = spawnSync("git", args, { cwd, input, maxBuffer: 64 * 1024 * 1024 });

    if (result.error) {
        throw result.error;
    }

    if (result.status !== 0) {
        throw new Error(result.stderr.toString().trim() || `git ${args[0]} failed`);
    }

    return result.stdout;
};

const excludedPath = (filename) =>
    /(?:^|\/)(?:readme|roadma?p)(?:[._-][^/]*)?$/i.test(filename) ||
    /(?:^|\/)docs\//i.test(filename) ||
    /(?:^|\/)(?:[^/]+\.lockb?|(?:package-lock|npm-shrinkwrap|packages\.lock)\.json|pnpm-lock\.ya?ml|go\.sum|Package\.resolved|\.terraform\.lock\.hcl)$/i.test(
        filename,
    ) ||
    /(?:^|\/)(?:node_modules|vendor|dist|build|out|target|coverage|generated|__generated__|\.next|\.nuxt|\.output)(?:\/|$)/i.test(
        filename,
    ) ||
    /(?:\.(?:generated|gen|g)\.[^/]+|\.min\.(?:js|css)|\.map|\.pb\.(?:go|cc|h)|_pb2(?:_grpc)?\.py)$/i.test(
        filename,
    );

const commentPattern = (filename) => {
    if (/\.(?:mdx?|html?|xml|xhtml|svg|vue|svelte)$/i.test(filename)) {
        return /^<!--[\s\S]*?-->/;
    }

    if (
        /(?:\.(?:py|pyi|sh|bash|zsh|fish|rb|rake|pl|pm|r|jl|ya?ml|toml|nix|tf|hcl|graphql|gql|ps1|psm1|cmake)|(?:^|\/)(?:Dockerfile|Makefile|Gemfile|CMakeLists\.txt))$/i.test(
            filename,
        )
    ) {
        return /^#[^\r\n]*/;
    }

    if (/\.sql$/i.test(filename)) {
        return /^(?:--[^\r\n]*|\/\*[\s\S]*?\*\/)/;
    }

    if (
        /\.(?:[cm]?[jt]sx?|c|h|cc|hh|cpp|hpp|cxx|hxx|m|mm|java|go|rs|cs|css|scss|less|swift|kt|kts|scala|dart|proto|php|fs|fsx|v|sv|sol|jsonc)$/i.test(
            filename,
        )
    ) {
        return /^(?:\/\/[^\r\n]*|\/\*[\s\S]*?\*\/)/;
    }

    return null;
};

// Only the leading comments count: a marker in a string or after code exempts nothing.
const generatedHeader = (filename, header) => {
    const comment = commentPattern(filename);

    if (!comment) {
        return false;
    }

    let remaining = header.toString("utf8").replace(/^﻿?(?:#![^\r\n]*(?:\r\n?|\n|$))?/, "");

    for (;;) {
        const match = comment.exec(remaining.trimStart());

        if (!match) {
            return false;
        }

        if (
            /@generated\b|<auto-generated\b|automatically generated|\bcode generated\b|\bgenerated[^\r\n]*do not edit/i.test(
                match[0],
            )
        ) {
            return true;
        }

        remaining = remaining.trimStart().slice(match[0].length);
    }
};

// Read only the first bytes of a blob, however large it is.
const blobHeader = (cwd, oid) =>
    new Promise((resolve, reject) => {
        const child = spawn("git", ["cat-file", "blob", oid], {
            cwd,
            stdio: ["ignore", "pipe", "pipe"],
        });
        const chunks = [];
        let size = 0;
        let stderr = "";

        child.on("error", reject);
        child.stderr.on("data", (chunk) => {
            stderr += chunk;
        });
        child.stdout.on("data", (chunk) => {
            if (size === HEADER_BYTES) {
                return;
            }

            const part = chunk.subarray(0, HEADER_BYTES - size);

            chunks.push(part);
            size += part.length;

            if (size === HEADER_BYTES) {
                child.kill();
            }
        });
        child.on("close", (code, signal) => {
            if (code === 0 || (size === HEADER_BYTES && signal === "SIGTERM")) {
                resolve(Buffer.concat(chunks, size));
            } else {
                reject(new Error(stderr.trim() || `Cannot read staged blob ${oid}`));
            }
        });
    });

// Regular files at stage 0; symlinks (120000) and submodules (160000) are not files of this repo.
const indexFiles = (cwd) => {
    const entries = git(cwd, ["ls-files", "--stage", "-z"]).toString().split("\0").filter(Boolean);

    return entries.flatMap((entry) => {
        const tab = entry.indexOf("\t");
        const [mode, oid, stage] = entry.slice(0, tab).split(" ");
        const filename = entry.slice(tab + 1);
        const regular = ["100644", "100755"].includes(mode) && stage === "0";

        return regular && !excludedPath(filename) ? [{ filename, oid }] : [];
    });
};

const withSizes = (cwd, files) => {
    if (!files.length) {
        return [];
    }

    const input = files.map((file) => `${file.oid}\n`).join("");
    const sizes = git(cwd, ["cat-file", "--batch-check=%(objectsize)"], input)
        .toString()
        .trimEnd()
        .split("\n");

    return files.map((file, i) => {
        if (!/^\d+$/.test(sizes[i])) {
            throw new Error(`Cannot size staged file ${JSON.stringify(file.filename)}`);
        }

        return { ...file, bytes: Number(sizes[i]) };
    });
};

const markedGenerated = (cwd, files) => {
    const input = files.map((file) => `${file.filename}\0`).join("");
    const attributes = git(
        cwd,
        ["check-attr", "--cached", "-z", "--stdin", "linguist-generated", "linguist-vendored"],
        input,
    )
        .toString()
        .split("\0");
    const marked = new Set();

    for (let i = 0; i + 2 < attributes.length; i += 3) {
        if (["set", "true"].includes(attributes[i + 2])) {
            marked.add(attributes[i]);
        }
    }

    return marked;
};

// The staged baseline, so a commit that splits a file can drop its entry in the same commit.
const baseline = (cwd) => {
    const found = spawnSync("git", ["show", `:${BASELINE}`], { cwd, maxBuffer: 1024 * 1024 });

    if (found.status !== 0) {
        return new Set();
    }

    const lines = found.stdout.toString().split(/\r?\n/);

    return new Set(
        lines.map((line) => line.trim()).filter((line) => line && !line.startsWith("#")),
    );
};

const oversized = async (cwd) => {
    const large = withSizes(cwd, indexFiles(cwd)).filter((file) => file.bytes > LIMIT);

    if (!large.length) {
        return [];
    }

    const marked = markedGenerated(cwd, large);
    const found = [];

    for (const file of large.filter((candidate) => !marked.has(candidate.filename))) {
        const header = await blobHeader(cwd, file.oid);

        if (!header.includes(0) && !generatedHeader(file.filename, header)) {
            found.push(file);
        }
    }

    return found;
};

const quote = (value) => `'${value.replaceAll("'", "'\\''")}'`;

const report = (violations, stale) => {
    if (violations.length) {
        console.error(
            `ERROR: files exceed 5000 tokens (${LIMIT} bytes; 1 token = 4 bytes) and are not in ${BASELINE}:`,
        );

        for (const { filename, bytes } of violations) {
            console.error(
                `  ${JSON.stringify(filename)}: ${bytes} bytes / ${bytes / 4} tokens; split into at least ${Math.ceil(bytes / LIMIT)} files.`,
            );
            console.error(`    Inspect the staged version: git show ${quote(`:${filename}`)}`);
        }

        console.error(
            "1. Split by responsibility: move independent functions/types/components into named modules; move tests/fixtures into separate files.",
        );
        console.error(
            `2. Update imports/exports and callers; keep EVERY resulting file at or below ${LIMIT} bytes.`,
        );
        console.error(
            "3. Stage the intended files with git add -- <original> <new-files>, review git diff --cached, then retry.",
        );
        console.error(
            `Generated/vendored files only: mark their exact paths linguist-generated=true or linguist-vendored=true in .gitattributes and stage it. Do not exempt hand-written code or add it to ${BASELINE}.`,
        );
    }

    if (stale.length) {
        console.error(
            `ERROR: ${BASELINE} lists files that no longer exceed the limit; remove them:`,
        );

        for (const filename of stale) {
            console.error(`  ${filename}`);
        }
    }
};

const main = async () => {
    const cwd = git(process.cwd(), ["rev-parse", "--show-toplevel"]).toString().trim();
    const found = await oversized(cwd);
    const allowed = baseline(cwd);
    const violations = found.filter((file) => !allowed.has(file.filename));
    const names = new Set(found.map((file) => file.filename));
    const stale = [...allowed].filter((filename) => !names.has(filename));

    report(violations, stale);

    if (violations.length || stale.length) {
        process.exitCode = 1;
    }
};

await main();
