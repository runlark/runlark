// Runs scripts/file-limit.mjs on throwaway repositories: `node --test scripts/file-limit.test.mjs`.
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { after, test } from "node:test";
import { fileURLToPath } from "node:url";

const SCRIPT = join(dirname(fileURLToPath(import.meta.url)), "file-limit.mjs");
// A hook exports GIT_DIR, GIT_INDEX_FILE and friends; they must not reach the throwaway repositories.
const ENV = Object.fromEntries(
    Object.entries(process.env).filter(([key]) => !key.startsWith("GIT_")),
);
const roots = [];

after(() => {
    for (const root of roots) {
        rmSync(root, { recursive: true, force: true });
    }
});

const run = (cwd, command, args) => {
    const result = spawnSync(command, args, { cwd, env: ENV, encoding: "utf8" });

    if (result.error) {
        throw result.error;
    }

    return result;
};

const repository = () => {
    const root = mkdtempSync(join(tmpdir(), "file-limit-"));

    roots.push(root);
    assert.equal(run(root, "git", ["init", "-q"]).status, 0);

    const write = (name, content) => {
        mkdirSync(dirname(join(root, name)), { recursive: true });
        writeFileSync(join(root, name), content);
    };

    const stage = (files) => {
        for (const [name, content] of Object.entries(files)) {
            write(name, content);
        }

        assert.equal(run(root, "git", ["add", "--", ...Object.keys(files)]).status, 0);
    };

    return { write, stage, check: () => run(root, process.execPath, [SCRIPT]) };
};

const text = (bytes) => "x".repeat(bytes);

test("a file of exactly 20000 bytes passes and one byte more fails", () => {
    const repo = repository();

    repo.stage({ "src/fits.rs": text(20_000) });
    assert.equal(repo.check().status, 0);

    repo.stage({ "src/big.rs": text(20_001) });
    const result = repo.check();

    assert.equal(result.status, 1);
    assert.match(result.stderr, /"src\/big\.rs": 20001 bytes/);
    assert.doesNotMatch(result.stderr, /fits\.rs/);
});

test("the staged content decides, not the working copy", () => {
    const repo = repository();

    repo.stage({ "a.ts": "small" });
    repo.write("a.ts", text(30_000));
    assert.equal(repo.check().status, 0);

    repo.stage({ "b.ts": text(30_000) });
    repo.write("b.ts", "small again");
    assert.equal(repo.check().status, 1);
});

test("the baseline admits a listed file and fails on an entry that no longer exceeds", () => {
    const repo = repository();

    repo.stage({ "old.md": text(25_000), "file-limit.baseline": "# debt\nold.md\n" });
    assert.equal(repo.check().status, 0);

    repo.stage({ "old.md": "split" });
    const result = repo.check();

    assert.equal(result.status, 1);
    assert.match(result.stderr, /no longer exceed the limit[\s\S]*old\.md/);
});

test("generated, vendored, binary and documentation files are exempt", () => {
    const repo = repository();

    repo.stage({
        ".gitattributes": "gen/** linguist-generated=true\nthird/** linguist-vendored=true\n",
        "gen/schema.json": text(30_000),
        "third/lib.js": text(30_000),
        "src/api.rs": `// @generated by a tool\n${text(30_000)}`,
        "image.bin": Buffer.concat([Buffer.from([0]), Buffer.alloc(30_000, 1)]),
        "docs/guide.md": text(30_000),
        "README.md": text(30_000),
        "Cargo.lock": text(30_000),
    });

    assert.equal(repo.check().status, 0);
});

test("a generated marker after code exempts nothing", () => {
    const repo = repository();

    repo.stage({ "src/main.rs": `fn main() {}\n// @generated\n${text(30_000)}` });
    assert.equal(repo.check().status, 1);
});
